  static List<YogaPose> byDifficulty(PoseDifficulty difficulty) =>
      all.where((YogaPose pose) => pose.difficulty == difficulty).toList();

  static YogaPose byId(String id) =>
      all.firstWhere((YogaPose pose) => pose.id == id);

  static List<YogaPose> search(String query) {
    final String q = query.trim().toLowerCase();
    if (q.isEmpty) {
      return all;
    }
    return all
        .where(
          (YogaPose pose) =>
              pose.name.toLowerCase().contains(q) ||
              pose.sanskritName.toLowerCase().contains(q) ||
              pose.focus.toLowerCase().contains(q),
        )
        .toList();
  }
